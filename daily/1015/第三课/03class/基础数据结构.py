#列表写法和变量类似，用中括号括起来，每个元素用逗号分隔
fruits = ['苹果','香蕉','鸭梨',100]#可以存储不同数据类型
#索引(下标)：0     1     2     3
fruits[0] = '西瓜' #列表名后面加上中括号，中括号里面还带有数字，就指的是列表里面的具体元素
#我们编程里面，第一个元素的下标用0表示
print(fruits)


#元组，和列表的区别是不可变
money = ('钱',100,50,20)
#money[0] = 10,元组不允许修改
print(money[0])


#键值对(字典)，用大括号
user = {'小明': '1122'}#第一个元素叫键，第二个元素叫值
print(user['小明'])#通过键去找对应的值